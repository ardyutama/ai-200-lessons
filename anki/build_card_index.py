#!/usr/bin/env python3
"""Regenerate anki/card-index-by-tag.md from the TSV sources.

Usage: python anki/build_card_index.py

Reads anki/ai200-basic.tsv and anki/ai200-cloze.tsv (retake1 Notes only) and the
sprint calendar in validate_deck.SPRINT_DAYS. Run it after any tag or text change,
then review `git diff anki/card-index-by-tag.md`.
"""
import csv
import re
from collections import defaultdict
from datetime import date
from pathlib import Path

from validate_deck import SPRINT_DAYS

HERE = Path(__file__).parent
DOMAIN_ORDER = ["ai200::integration", "ai200::containers", "ai200::data", "ai200::ops"]
META_TAGS = {"retake1", "cloze"}
CLOZE_RE = re.compile(r"\{\{c(\d+)::")


def retake_notes():
    """Return (kind, front, tags, cards) for every retake1 Note, basic first then cloze."""
    notes = []
    for kind in ("basic", "cloze"):
        with open(HERE / f"ai200-{kind}.tsv", encoding="utf-8") as f:
            for row in csv.reader(f, delimiter="\t"):
                if len(row) < 3 or row[0].startswith("#"):
                    continue
                tags = row[2].split()
                if "retake1" in tags:
                    cards = len(set(CLOZE_RE.findall(row[0]))) if kind == "cloze" else 1
                    notes.append((kind, row[0], tags, cards))
    return notes


def sprint_table(notes):
    lines = ["## Sprint days",
             "",
             "Each day's filtered deck uses the cumulative search below (`is:new` rolls leftovers forward). "
             "Notes and Cards are what that day newly adds.",
             "",
             "| Day | Adds tags | Notes | Cards | Search |",
             "|---|---|---|---|---|"]
    claimed, cumulative = set(), []
    for iso, day_tags in SPRINT_DAYS.items():
        cumulative += day_tags
        new = [i for i, (_, _, tags, _) in enumerate(notes)
               if i not in claimed and set(cumulative) & set(tags)]
        claimed.update(new)
        d = date.fromisoformat(iso)
        search = "deck:AI-200 tag:retake1 is:new (" + " OR ".join(f"tag:{t}" for t in cumulative) + ")"
        lines.append(f"| {d:%a %b} {d.day} | {', '.join(day_tags)} | {len(new)} | "
                     f"{sum(notes[i][3] for i in new)} | `{search}` |")
    lines += ["", f"Notes reached by no day: {len(notes) - len(claimed)}.", ""]
    return lines


def main():
    notes = retake_notes()
    n_basic = sum(1 for kind, *_ in notes if kind == "basic")
    lines = ["# AI-200 retake deck — card index by tag",
             "",
             "Generated by `anki/build_card_index.py`; do not edit by hand.",
             "",
             f"{len(notes)} Notes ({n_basic} basic + {len(notes) - n_basic} cloze) = "
             f"{sum(n[3] for n in notes)} Cards, all tagged `retake1`. Notes are grouped under their "
             "domain; a tag shared across domains (e.g. `servicebus`, `scenario`) appears once per domain "
             "with only that domain's Notes. Drill search pattern: `deck:AI-200 tag:retake1 tag:TAG` "
             "(combine tags freely). `mock01` marks the Notes that fix the ten Mock-01 misses.",
             ""]
    lines += sprint_table(notes)

    by_pair = defaultdict(set)  # (domain, topic tag) -> {fronts}
    for _, front, tags, _ in notes:
        for t in tags:
            if not t.startswith("ai200::") and t not in META_TAGS:
                by_pair[(tags[0], t)].add(front)
    for domain in DOMAIN_ORDER:
        lines.append(f"## {domain}")
        for tag in sorted({t for d, t in by_pair if d == domain}):
            fronts = sorted(by_pair[(domain, tag)])
            lines.append(f"### `{tag}` ({len(fronts)})")
            for front in fronts:
                snippet = front if len(front) <= 110 else front[:107].rstrip() + "..."
                lines.append(f"- {snippet}")
            lines.append("")
    (HERE / "card-index-by-tag.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"card-index-by-tag.md: {len(notes)} Notes, {len(by_pair)} domain-tag groups")


if __name__ == "__main__":
    main()
